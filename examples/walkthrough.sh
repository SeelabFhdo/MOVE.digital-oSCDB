#!/usr/bin/env bash
# Runs a tour through the OSCDB API against a running instance and prints it as Markdown:
# every command followed by its real output. docs/example.md is generated with:
#
#   examples/walkthrough.sh > docs/example.md
#
# BASE defaults to http://localhost:8080. Needs curl and jq; the inquiry steps need Ollama (see docs/inquiries.md).
set -euo pipefail

BASE=${BASE:-http://localhost:8080}
SHOWN=http://localhost:8080   # URL printed in the Markdown, independent of BASE

# Prints a step: heading, explanation, the command as shown to the reader, then its output.
# The command is run through bash with $BASE set, and printed with $BASE replaced by $SHOWN.
step() {
  local title=$1 text=$2 cmd=$3 lang=${4:-json}
  printf '### %s\n\n%s\n\n```bash\n%s\n```\n\n' "$title" "$text" "${cmd//\$BASE/$SHOWN}"
  printf '```%s\n' "$lang"
  BASE=$BASE bash -c "$cmd" 2>&1 | sed -e '$a\'
  printf '```\n\n'
}

# Submits an inquiry and waits for it; prints the job id.
inquire() {
  local id status
  id=$(jq -n --arg q "$2" --arg f "$1" '{question: $q, format: $f}' |
    curl -sf -H 'Content-Type: application/json' -d @- "$BASE/api/v1/inquiries" | jq -r .id)
  while status=$(curl -sf "$BASE/api/v1/inquiries/$id" | jq -r .status); [[ $status == QUEUED || $status == RUNNING ]]; do
    sleep 2
  done
  echo "$id"
}

# Prints the three calls of an inquiry (submit, poll, download) with real output.
inquiry_steps() {
  local n=$1 format=$2 question=$3 lang=$4 shorten=$5
  local id started=$SECONDS
  id=$(inquire "$format" "$question")
  local took=$((SECONDS - started))
  local body
  body=$(jq -n --arg q "$question" --arg f "$format" '{question: $q, format: $f}' -c)
  printf '### %s. Inquiry: %s\n\n' "$n" "$question"
  printf 'Submit the question with format `%s`. The answer is `202 Accepted` with the job id:\n\n' "$format"
  printf '```bash\ncurl -s -X POST %s/api/v1/inquiries \\\n  -H '"'"'Content-Type: application/json'"'"' \\\n  -d '"'"'%s'"'"'\n```\n\n' "$SHOWN" "$body"
  printf '```json\n{"id":"%s","status":"QUEUED","queuePosition":1,...}\n```\n\n' "$id"
  printf 'Poll the job until `status` is `DONE` (this one took %s s). `meta` shows the generated SQL and every assumption:\n\n' "$took"
  printf '```bash\ncurl -s %s/api/v1/inquiries/%s | jq '"'"'{status, error, meta: (.meta | {sql, assumptions, feeds, rowCount, truncated, attempts})}'"'"'\n```\n\n' "$SHOWN" "$id"
  printf '```json\n'
  curl -sf "$BASE/api/v1/inquiries/$id" | jq '{status, error, meta: (.meta | {sql, assumptions, feeds, rowCount, truncated, attempts})}'
  printf '```\n\n'
  printf 'Download the result:\n\n```bash\ncurl -s %s/api/v1/inquiries/%s/result%s\n```\n\n' "$SHOWN" "$id" "$shorten"
  printf '```%s\n' "$lang"
  BASE=$BASE bash -c "curl -sf $BASE/api/v1/inquiries/$id/result$shorten" | sed -e '$a\'
  printf '```\n\n'
}

curl -sf "$BASE/api/v1/feeds?size=1" > /dev/null || { echo "OSCDB is not reachable at $BASE" >&2; exit 1; }

cat <<EOF2
# Walkthrough: from timetable lookups to natural-language inquiries

This page is generated by [\`examples/walkthrough.sh\`](../examples/walkthrough.sh) against a running instance
(started with \`docker compose -f compose.deploy.yaml up -d --build\`, see [deployment.md](deployment.md)).
Every output below is real. Regenerate it with \`examples/walkthrough.sh > docs/example.md\`.

Generated on $(date '+%Y-%m-%d') with all 19 DSW21 feeds imported. Inquiry answers come from the local model
and can differ slightly between runs.

## Part 1: REST lookups

EOF2

step "1. Which timetable is current?" \
  "\`current\` is the feed valid today. Today no feed covers the date, so OSCDB falls back to the latest feed and says so with \`\"fallback\": true\` (and the header \`OSCDB-Feed-Fallback: true\`)." \
  'curl -s $BASE/api/v1/feeds/current | jq'

step "2. Find a station by name" \
  "Name search is case-insensitive and tolerant of partial names." \
  'curl -s "$BASE/api/v1/feeds/current/stations?q=reinoldi" | jq'

step "3. Station details with its platforms" \
  "A station groups all platforms (stops) with the same name; its id is a slug that stays the same across timetables." \
  'curl -s $BASE/api/v1/feeds/current/stations/reinoldikirche-u | jq -c "{id, name, lat, lon, platforms: [.platforms[].id]}"'

step "4. Departures at that station" \
  "Departures merged over all platforms, for a date inside the timetable, from 18:00, the next 5." \
  'curl -s "$BASE/api/v1/stations/reinoldikirche-u/departures?date=2026-07-01&from=18:00&limit=5" | jq "{serviceDate, departures: [.departures[] | {time, line: .routeShortName, headsign, platform: .stopId}]}"'

step "5. Errors are problem+json" \
  "Unknown ids and invalid parameters return RFC 9457 problem details." \
  'curl -s $BASE/api/v1/feeds/current/stations/does-not-exist | jq'

cat <<'EOF2'
## Part 2: Natural-language inquiries

Ask in plain language, choose `json`, `csv`, `xml` or `geojson`, then poll the job. See [inquiries.md](inquiries.md).

EOF2

inquiry_steps 6 csv "Top 5 busiest stations by number of departures on 2026-07-01" csv ""
inquiry_steps 7 geojson "All stops within 300 m of 51.5153, 7.4687" json " | jq '{type, features: [.features[:2][] | {geometry, properties}]}'"
inquiry_steps 8 json "Compare the number of lines between the first timetable of 2023 and the latest timetable" json " | jq .rows"

step "9. An invalid format is rejected at once" \
  "Input errors do not create a job." \
  "curl -s -X POST \$BASE/api/v1/inquiries -H 'Content-Type: application/json' -d '{\"question\": \"Which lines exist?\", \"format\": \"pdf\"}' | jq"
